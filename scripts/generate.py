#!/usr/bin/env python3
"""Generate src/advernue/_generated/ from spec/openapi.json (stdlib only).

Usage: python scripts/generate.py [--spec spec/openapi.json] [--out src/advernue/_generated]
"""
from __future__ import annotations

import argparse
import json
import keyword
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# ruff: noqa\n# mypy: ignore-errors\n# Generated by scripts/generate.py from spec/openapi.json. Do not edit.\n"
# Parameters handled by the client itself, never exposed as plain query/header args.
RESERVED = {"Idempotency-Key", "dry_run"}


def snake(s: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", s)
    s = re.sub(r"[^0-9a-zA-Z]+", "_", s).lower().strip("_")
    return s + "_" if keyword.iskeyword(s) or s in {"self", "body"} else s


def pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9a-zA-Z]+", s) if p)


class Models:
    """Turns JSON schemas into TypedDict definitions plus type-expression strings."""

    def __init__(self, spec: dict) -> None:
        self.comps: dict = spec["components"]["schemas"]
        self.defs: dict[str, str] = {}  # name -> source
        self.by_json: dict[str, str] = {}
        self.platform = json.dumps(self.comps["Platform"].get("enum"))
        for name, sch in self.comps.items():
            self.by_json.setdefault(json.dumps(sch, sort_keys=True), name)
        for name, sch in self.comps.items():
            self.define(name, sch, top=True)

    def ty(self, s: dict, hint: str) -> str:
        if "$ref" in s:
            n = s["$ref"].rsplit("/", 1)[-1]
            return n if n in self.comps else "Any"
        key = json.dumps(s, sort_keys=True)
        if key in self.by_json and s.get("type") == "object":
            return self.by_json[key]
        if "const" in s:
            return f"Literal[{s['const']!r}]"
        if "enum" in s:
            if json.dumps(s["enum"]) == self.platform:
                return "Platform"
            return f"Literal[{', '.join(repr(v) for v in s['enum'])}]"
        for k in ("anyOf", "oneOf"):
            if k in s:
                return self.union([self.ty(x, hint) for x in s[k]])
        t = s.get("type")
        if isinstance(t, list):
            return self.union([self.ty({**s, "type": x}, hint) for x in t])
        if t == "object" or "properties" in s:
            if s.get("properties"):
                return self.define(hint, s)
            ap = s.get("additionalProperties")
            return f"Dict[str, {self.ty(ap, hint + 'Value')}]" if isinstance(ap, dict) and ap else "Dict[str, Any]"
        if t == "array":
            return f"List[{self.ty(s.get('items', {}), hint + 'Item')}]"
        return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}.get(t, "Any")

    @staticmethod
    def union(parts: list[str]) -> str:
        out = list(dict.fromkeys(parts))
        return out[0] if len(out) == 1 else f"Union[{', '.join(out)}]"

    def define(self, name: str, s: dict, top: bool = False) -> str:
        key = json.dumps(s, sort_keys=True)
        if not top and key in self.by_json:
            return self.by_json[key]
        base, i = name, 2
        while name in self.defs and not top:
            name, i = f"{base}{i}", i + 1
        self.by_json.setdefault(key, name)
        self.defs[name] = ""  # reserve (recursion safe)
        req = set(s.get("required", []))
        fields = {p: self.ty(v, name + pascal(p)) for p, v in s.get("properties", {}).items()}
        r = {p: t for p, t in fields.items() if p in req}
        o = {p: t for p, t in fields.items() if p not in req}
        doc = f'    """{s["description"].replace(chr(34) * 3, "").replace(chr(92), "")}"""\n' if s.get("description") else ""

        def fn(n: str, d: dict, total: bool) -> str:
            body = ", ".join(f'"{p}": "{t}"' for p, t in d.items())
            return f'{n} = TypedDict("{n}", {{{body}}}{"" if total else ", total=False"})\n'

        if r and o:
            src = fn(f"_{name}Req", r, True) + fn(f"_{name}Opt", o, False)
            tail = doc or "    pass\n"
            src += f"\n\nclass {name}(_{name}Req, _{name}Opt):\n{tail}"
        else:
            src = fn(name, r or o, bool(r))
        self.defs[name] = src
        return name

    def render(self) -> str:
        enums = "".join(
            f"{n} = Literal[{', '.join(repr(v) for v in s['enum'])}]\n"
            for n, s in self.comps.items()
            if "enum" in s
        )
        typed = {n: d for n, d in self.defs.items() if n not in {k for k, v in self.comps.items() if "enum" in v}}
        # Non-object components (aliases) are rendered by define() as empty TypedDicts; skip them.
        body = "\n\n".join(d for n, d in typed.items() if not (n in self.comps and "properties" not in self.comps[n]))
        aliases = "".join(
            f"{n} = {self.ty(s, n)}\n"
            for n, s in self.comps.items()
            if "enum" not in s and "properties" not in s
        )
        names = sorted(self.comps) + [n for n in self.defs if n not in self.comps]
        return (
            HEADER
            + "from __future__ import annotations\n\nfrom typing import Any, Dict, List, Literal, TypedDict, Union\n\n"
            + f"__all__ = {sorted(set(names))!r}\n\n"
            + enums + "\n" + aliases + "\n\n" + body + "\n"
        )


def esc(s: str) -> str:
    return " ".join(s.replace("\\", "/").replace('"', "'").split())


def gen_ops(spec: dict, m: Models) -> tuple[dict[str, list[str]], list[str]]:
    ns: dict[str, list[tuple]] = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            tag, name = op["operationId"].split(".", 1)
            ns.setdefault(tag, []).append((path, method.upper(), op, snake(name)))
    return ns, sorted(ns)


def render_api(spec: dict, m: Models, is_async: bool) -> str:
    ns, tags = gen_ops(spec, m)
    a = "Async" if is_async else ""
    kw = "async def" if is_async else "def"
    aw = "await " if is_async else ""
    out = [HEADER, "from __future__ import annotations\n\nfrom typing import Any, Dict, List, Literal, Optional, Union\nfrom urllib.parse import quote as _q\n\nfrom .models import *\n\n"]
    for tag in tags:
        cls = f"{a}{pascal(tag)}API"
        out.append(f'\nclass {cls}:\n    """{esc(tag)} operations."""\n\n    def __init__(self, c: "{a}Namespaces") -> None:\n        self._c = c\n')
        seen = set()
        for path, method, op, mname in sorted(ns[tag], key=lambda x: x[3]):
            assert mname not in seen, op["operationId"]
            seen.add(mname)
            write = method != "GET"
            pos, kwo, qmap = [], [], []
            fpath = path
            for p in op.get("parameters", []):
                if p["name"] in RESERVED or p["in"] not in ("path", "query"):
                    continue
                t = m.ty(p["schema"], pascal(op["operationId"]) + pascal(p["name"]))
                py = snake(p["name"])
                if p["in"] == "path":
                    pos.append(f"{py}: {t}")
                    fpath = fpath.replace("{" + p["name"] + "}", "{_q(str(" + py + "), safe='')}")
                elif p.get("required"):
                    kwo.insert(0, f"{py}: {t}")
                    qmap.append(f'"{p["name"]}": {py}')
                else:
                    kwo.append(f"{py}: Optional[{t}] = None")
                    qmap.append(f'"{p["name"]}": {py}')
            rb = op.get("requestBody")
            bsig = ""
            if rb:
                bt = m.ty(rb["content"]["application/json"]["schema"], pascal(op["operationId"]) + "Body")
                bsig = f"body: {bt}" if rb.get("required") else f"body: Optional[{bt}] = None"
            if write:
                kwo += ["idempotency_key: Optional[str] = None", "dry_run: bool = False"]
            req_pos = pos + ([bsig] if bsig and "=" not in bsig else [])
            opt_pos = [bsig] if bsig and "=" in bsig else []
            sig = ", ".join(["self"] + req_pos + opt_pos + (["*"] + kwo if kwo else []))
            # response
            ret = "None"
            for code in sorted(op["responses"]):
                if code.startswith("2") and code != "204":
                    ct, v = next(iter(op["responses"][code].get("content", {}).items()), (None, None))
                    if ct == "application/json":
                        ret = m.ty(v["schema"], pascal(op["operationId"]) + "Response")
                    elif ct and (ct.startswith("text/") or "javascript" in ct):
                        ret = "str"
                    elif ct:
                        ret = "bytes"
                    break
            call = [f'"{method}"', f'f"{fpath}"']
            if qmap:
                call.append("query={" + ", ".join(qmap) + "}")
            if bsig:
                call.append("body=body")
            if write:
                call += ["idempotency_key=idempotency_key", "dry_run=dry_run"]
            out.append(f'\n    {kw} {mname}({sig}) -> {ret}:\n        """{esc(op.get("summary", ""))} ({method} {path})"""\n        return {aw}self._c._request({", ".join(call)})\n')
    out.append(f"\n\nclass {a}Namespaces:\n    def __init__(self) -> None:\n")
    out += [f"        self.{snake(t)} = {a}{pascal(t)}API(self)\n" for t in tags]
    out.append(
        f"\n    {kw} _request(self, method: str, path: str, *, query: Optional[Dict[str, Any]] = None, body: Any = None, idempotency_key: Optional[str] = None, dry_run: bool = False) -> Any:\n        raise NotImplementedError\n"
    )
    return "".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=str(ROOT / "spec/openapi.json"))
    ap.add_argument("--out", default=str(ROOT / "src/advernue/_generated"))
    args = ap.parse_args()
    spec = json.loads(Path(args.spec).read_text())
    m = Models(spec)
    # api modules must be rendered first so inline request/response models are registered
    sync, asyn = render_api(spec, m, False), render_api(spec, m, True)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "models.py").write_text(m.render())
    (out / "sync_api.py").write_text(sync)
    (out / "async_api.py").write_text(asyn)
    (out / "__init__.py").write_text(HEADER)
    print(f"generated {len(m.defs)} models, {sum(len(v) for v in gen_ops(spec, m)[0].values())} operations")


if __name__ == "__main__":
    main()
